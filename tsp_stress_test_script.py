def run_case(n: int, seed: int, kind: str,
             K=5, L=6, TAU=0.30, M=25, MAX_2OPT_PASSES=2, hk_limit: int = 10):
    print(f"\n=== n={n}, seed={seed}, kind={kind} ===")
    mat = generate_matrix(n, seed, kind)

    # Beam timing/memory ONLY
    tracemalloc.start()
    t0 = time.perf_counter()
    b_cost, b_route = tsp_structural_beam(mat, K=K, L=L, TAU=TAU, M=M, MAX_2OPT_PASSES=MAX_2OPT_PASSES)
    t1 = time.perf_counter()
    cur, peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    beam_time = t1 - t0
    beam_mem_mb = peak / (1024*1024)

    if b_route is None:
        print("Beam: No complete tour found.")
    else:
        print(f"Beam cost : {b_cost}")
        print("Beam route:", " -> ".join(map(str, b_route)))
    print(f"Beam time : {beam_time:.6f}s | Peak mem: {beam_mem_mb:.3f} MB")

    # Verification
    if n <= hk_limit:
        hk_cost, hk_route = held_karp_tsp(mat)
        if hk_cost is None:
            print("HK: No Hamiltonian cycle exists (given blocks).")
            verified = (b_route is None)
        else:
            print(f"HK cost  : {hk_cost}")
            print("HK route :", " -> ".join(map(str, hk_route)))
            verified = (b_cost <= hk_cost) if b_cost is not None else False

        if verified:
            print("✅ MATCH — beam found optimal tour (HK verified).")
        else:
            print("❌ MISMATCH — investigate. Matrix follows:")
            for row in mat:
                print("  ", ["INF" if math.isinf(x) else int(x) for x in row])
    else:
        print(f"(HK skipped for n={n}; limit={hk_limit})")

