# Held–Karp exact TSP (verification only; exponential)
# -----------------------------------------------------------------------------
def held_karp_tsp(matrix: List[List[float]]) -> Tuple[Optional[int], Optional[List[int]]]:
    n = len(matrix)
    INF = float('inf')
    dp = {}
    for j in range(1, n):
        w = matrix[0][j]
        if math.isinf(w):
            continue
        dp[(1<<0)|(1<<j), j] = (w, 0)

    for mask in range(1<<n):
        if not (mask & 1):
            continue
        for j in range(n):
            if j == 0 or not (mask & (1<<j)):
                continue
            if (mask, j) not in dp:
                continue
            cost_j, prev_j = dp[(mask, j)]
            for k in range(n):
                if (mask & (1<<k)) or math.isinf(matrix[j][k]):
                    continue
                nmask = mask | (1<<k)
                cand = cost_j + matrix[j][k]
                key = (nmask, k)
                if key not in dp or cand < dp[key][0]:
                    dp[key] = (cand, j)

    full = (1<<n) - 1
    best = None
    best_end = None
    for j in range(1, n):
        if (full, j) in dp and not math.isinf(matrix[j][0]):
            cand = dp[(full, j)][0] + matrix[j][0]
            if best is None or cand < best:
                best = cand
                best_end = j

    if best is None:
        return None, None

    tour = [0]
    mask = full
    j = best_end
    path_rev = [j]
    while j != 0:
        cost_j, prev_j = dp[(mask, j)]
        mask ^= (1<<j)
        j = prev_j
        if j != 0:
            path_rev.append(j)
    path_rev.reverse()
    tour.extend(path_rev)
    tour.append(0)
    return int(best), [x+1 for x in tour]

